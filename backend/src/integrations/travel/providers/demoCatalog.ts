export function getDemoOptions(category: TravelCategory): DemoOption[] {
  return options.filter((option) => option.category === category);
}

export function getDemoOption(
  category: TravelCategory,
  optionId: string,
): DemoOption | undefined {
  return options.find(
    (option) => option.category === category && option.id === optionId,
  );
}
